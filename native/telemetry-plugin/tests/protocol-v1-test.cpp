void framing(const Fixtures& f) {
  // Every two-way split of two small combined frames in each direction. The welcome and checkpoint pair of the TypeScript
  // test is split within 64 bytes of each frame edge: the frozen v0 parser takes about 6 ms per checkpoint under ASan.
  struct Pair { Sender sender; const char* a; const char* b; std::vector<std::string> kinds; bool every; };
  for (const auto& pair : {Pair{Sender::server, "clock-reply", "gap", {"clock.reply", "gap"}, true}, Pair{Sender::client, "hello", "ack-5", {"hello", "ack"}, true},
    Pair{Sender::server, "welcome", "checkpoint", {"welcome", "checkpoint"}, false}}) {
    const auto load = [&](const char* name) { return decode_payload(f.bytes(name), pair.sender); };
    const auto first = encode_frame(load(pair.a)); const auto combined = concat(first, encode_frame(load(pair.b)));
    const auto near_edge = [&](std::size_t at) { for (const auto edge : {std::size_t(0), first.size(), combined.size()}) if (at + 64 >= edge && at <= edge + 64) return true; return false; };
    unsigned splits = 0;
    for (std::size_t at = 0; at <= combined.size(); ++at) {
      if (!pair.every && !near_edge(at)) continue;
      FrameDecoder decoder(pair.sender); std::vector<std::string> kinds; const auto emit = [&](Message m) { kinds.push_back(m.kind); };
      decoder.push(combined.data(), at, emit); decoder.push(combined.data() + at, combined.size() - at, emit); decoder.end();
      check(kinds == pair.kinds, std::string("two-way split of ") + pair.a + "+" + pair.b); ++splits;
    }
    check(splits >= (pair.every ? combined.size() + 1 : 3 * 64), "split count");
  }
  for (const auto& name : {"event-job-configured-localized", "checkpoint-worst"}) {
    const auto expected = f.server(name); const auto frame = encode_frame(expected); FrameDecoder decoder(Sender::server); std::vector<Message> found;
    for (const auto& b : frame) decoder.push(&b, 1, [&](Message m) { found.push_back(std::move(m)); });
    decoder.end(); check(found.size() == 1 && canonical(found[0].wire) == canonical(expected.wire), std::string(name) + " byte at a time");
  }
  for (const auto& [sender, limit] : {std::pair<Sender, std::uint32_t>{Sender::server, 65536U}, std::pair<Sender, std::uint32_t>{Sender::client, 4096U}}) {
    auto exact = f.bytes(sender == Sender::server ? "welcome" : "hello"); exact.resize(limit, ' ');
    unsigned count = 0; FrameDecoder ok(sender); const auto frame = frame_of(exact); ok.push(frame.data(), frame.size(), [&](Message) { ++count; }); ok.end(); check(count == 1, "exact direction limit");
    for (const auto length : {0U, limit + 1, 0xffffffffU}) {
      std::uint8_t header[4]; for (unsigned i = 0; i < 4; ++i) header[i] = static_cast<std::uint8_t>((length >> (8 * i)) & 255);
      FrameDecoder d(sender); rejects([&] { d.push(header, 4, [](Message) {}); }, "length prefix bound", "payload size");
      const auto hello = frame_of(f.bytes("hello")); rejects([&] { d.push(hello.data(), hello.size(), [](Message) {}); }, "failed decoder stays closed", "closed");
    }
  }
  // A 4,097-byte client-size payload is legal from the server, but a server frame over 64 KiB is not.
  auto padded = f.bytes("welcome"); padded.resize(4097, ' '); FrameDecoder server_decoder(Sender::server); unsigned padded_count = 0;
  const auto padded_frame = frame_of(padded); server_decoder.push(padded_frame.data(), padded_frame.size(), [&](Message) { ++padded_count; }); check(padded_count == 1, "server accepts 4,097 bytes");
  const auto hello = encode_frame(f.client("hello"));
  for (const auto n : {std::size_t(1), std::size_t(3), std::size_t(4), hello.size() - 1}) {
    FrameDecoder d(Sender::client); d.push(hello.data(), n, [](Message) {}); rejects([&] { d.end(); }, "partial header or payload at EOF", "Truncated");
  }
  FrameDecoder clean(Sender::client); clean.end(); rejects([&] { clean.push(hello.data(), hello.size(), [](Message) {}); }, "clean EOF closes");
  const auto good = encode_frame(f.server("welcome")); const auto bad = concat(frame_of("{"), good); FrameDecoder malformed(Sender::server); unsigned emitted = 0;
  rejects([&] { malformed.push(bad.data(), bad.size(), [&](Message) { ++emitted; }); }, "malformed combined stream", "Malformed");
  check(emitted == 0, "no resynchronization"); rejects([&] { malformed.push(good.data(), good.size(), [&](Message) { ++emitted; }); }, "malformed decoder stays closed");
  const auto twice = concat(hello, hello);
  FrameDecoder recursive(Sender::client); unsigned recursive_emitted = 0;
  rejects([&] { recursive.push(hello.data(), hello.size(), [&](Message) { ++recursive_emitted; recursive.push(hello.data(), hello.size(), [&](Message) { ++recursive_emitted; }); }); }, "recursive push", "Recursive");
  check(recursive_emitted == 1, "recursive push emits no nested frames"); rejects([&] { recursive.push(hello.data(), hello.size(), [](Message) {}); }, "recursive decoder stays closed");
  FrameDecoder caught(Sender::client); unsigned caught_emitted = 0; bool caught_rejection = false;
  caught.push(twice.data(), twice.size(), [&](Message) {
    ++caught_emitted; try { caught.push(hello.data(), hello.size(), [&](Message) { ++caught_emitted; }); } catch (const ProtocolError&) { caught_rejection = true; }
  });
  check(caught_rejection && caught_emitted == 1, "caught recursive error still stops the chunk");
  FrameDecoder ending(Sender::client); unsigned seen = 0; ending.push(twice.data(), twice.size(), [&](Message) { if (++seen == 1) ending.end(); });
  check(seen == 1, "callback end stops the chunk"); rejects([&] { ending.push(hello.data(), hello.size(), [](Message) {}); }, "callback-ended decoder stays closed");
}

