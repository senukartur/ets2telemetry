export function appCopy(text: string, language: AppLanguage = 'en'): string {
  const key = APP_COPY_KEYS[text];
  return key ? t(key, undefined, language) : text;
}
/** Translate static label/template tables before interpolating game values. Keys, IDs and raw values are untouched. */
export function copyTable<T>(table: T, language: AppLanguage): T {
  if (language === 'en') return table;
  const translate = (value: unknown): unknown => typeof value === 'string' ? appCopy(value, language)
    : Array.isArray(value) ? value.map(translate)
    : value !== null && typeof value === 'object' ? Object.fromEntries(Object.entries(value).map(([key, entry]) => [key, translate(entry)])) : value;
  return translate(table) as T;
}

/** Application-formatted numeric evidence only; SDK names must never pass through this formatter. */
export function localizedMeasurement(text: string, language: AppLanguage): string {
  if (language === 'en') return text;
  const localized = /^(in |late by )/.test(text) ? localizeDeadlineString(text, language) : text;
  return localized.replace(/ (km\/h|mph|L\/100 km|US mpg|US gal|km|mi|L|rpm|t|lb)$/, (_match, unit: string) => ` ${translateUnit(unit === 'US gal' ? 'gal' : unit === 'US mpg' ? 'mpg' : unit, language)}`)
    .replace(/\(currency unknown\)$/, '(валюта неизвестна)').replace(/\(SDK-documented\)$/, '(подтверждено SDK)')
    .replace(/^Day (\d+),/, 'День $1,');
}
